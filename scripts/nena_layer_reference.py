"""
Write docs/standards/nena-sta-006.3-layers.md from NENA's own machine-readable schema.

    python scripts/nena_layer_reference.py [--schema <flatfile_schema_v3.yaml>]

The schema is NENA's NG911GISDataModel flat-file template (Apache-2.0), pinned to the commit the vendored
domains come from. The requirement level of each layer is from NENA-STA-006.3-2026 section 4 (the YAML doesn't
carry it). Field names and requirement flags are facts of the schema; descriptions are not copied.
"""
import argparse
import os
import urllib.request

import yaml

COMMIT = "30a42bfdf0eb316bb1266087f5f1a39e1c77e22d"
SCHEMA_URL = (f"https://raw.githubusercontent.com/NENA911/NG911GISDataModel/{COMMIT}/"
              "flatfile_templates/schema/v3.0/flatfile_schema_v3.yaml")
OUT = os.path.join(os.path.dirname(__file__), "..", "docs", "standards", "nena-sta-006.3-layers.md")

# STA-006.3 section 4 headings ("4.1.1 Road Centerlines—REQUIRED" ...)
LEVEL = {"RoadCenterLine": "Required", "SiteStructureAddressPoint": "Required",
         "SiteStructureAddressPolygon": "Recommended", "PsapPolygon": "Required", "PolicePolygon": "Required",
         "FirePolygon": "Required", "EmsPolygon": "Required", "ServiceBoundaryPolygon": "Strongly recommended",
         "ProvisioningPolygon": "Required", "A1Polygon": "Strongly recommended",
         "A2Polygon": "Strongly recommended", "A3Polygon": "Strongly recommended",
         "A4Polygon": "Strongly recommended", "A5Polygon": "Strongly recommended",
         "RailroadCenterLine": "Recommended", "HydrologyLine": "Recommended", "HydrologyPolygon": "Recommended",
         "DistanceMarkerPoint": "Recommended", "LocationMarkerPoint": "Recommended"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--schema")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    if a.schema:
        with open(a.schema) as f:
            d = yaml.safe_load(f)
    else:
        with urllib.request.urlopen(SCHEMA_URL, timeout=60) as r:
            d = yaml.safe_load(r.read())
    indicator = {x["layer_name"]: x["layer_indicator"] for x in d["gis_data_layers_registry"]}
    lines = [
        "# NENA-STA-006.3-2026 layers and fields",
        "",
        ("Generated by `scripts/nena_layer_reference.py` from NENA's flat-file schema "
        f"([NENA911/NG911GISDataModel@{COMMIT[:7]}]({SCHEMA_URL}), Apache-2.0, "
        "© National Emergency Number Association). Don't edit by hand."),
        "",
        ("Requirement levels are from the standard's section 4. \"Required fields\" are the ones the schema marks "
        "`field_is_required`; the standard calls many of the others *Conditional* (their business rules come from "
        "CLDXF-US or CLDXF-CA). Field definitions: section 5 of the standard ([summary](nena-sta-006.3.md))."),
        "",
        "| Layer | Indicator | Section | Geometry | Level | Required fields |",
        "|---|---|---|---|---|---|",
    ]
    for fc in d["feature_classes"]:
        req = [f["field_name"] for f in fc["fields"] if f["field_is_required"]]
        lines.append(f"| {fc['name']} | {indicator.get(fc['name'], '')} | {fc.get('section', '')} | "
                     f"{fc['geometry_type'].title()}{' Z' if fc.get('has_z') else ''} | "
                     f"{LEVEL.get(fc['name'], '')} | {', '.join(req)} |")
    lines += ["", "## Fields by layer", ""]
    for fc in d["feature_classes"]:
        rm = fc.get("country_specific_field_removals") or {}
        lines += [f"### {fc['name']}", ""]
        if any(rm.values()):
            lines += ["Not used in the US: " + (", ".join(rm.get("US", [])) or "none") +
                      ". Not used in Canada: " + (", ".join(rm.get("CA", [])) or "none") + ".", ""]
        lines += ["| Field | Alias | Type | Required | Domain |", "|---|---|---|---|---|"]
        for f in fc["fields"]:
            t = f["field_type"] + (f"({f['field_length']})" if f.get("field_length") else "")
            lines.append(f"| {f['field_name']} | {f['field_alias']} | {t} | "
                         f"{'yes' if f['field_is_required'] else ''} | {f.get('field_domain') or ''} |")
        lines.append("")
    lines += ["## Other registered layer names", "",
              ("The GIS Data Layers registry also names these (mostly service-boundary subtypes, same structure "
              "as the service boundary layers):"), "",
              ", ".join(f"{k} (`{v}`)" for k, v in indicator.items()
                        if k not in {fc["name"] for fc in d["feature_classes"]}), ""]
    with open(a.out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
