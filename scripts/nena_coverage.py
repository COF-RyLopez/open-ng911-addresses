"""
NENA field coverage across jobs (src/open_ng911/coverage.py): which fields each build fills, before and after
mapping the Sources' own fields, and which Required fields no Source has.

    python scripts/nena_coverage.py <job.json or CI build log> ...

Reads each job's `nena_coverage` from its job.json, or from the "NENA coverage by field" line a build prints
(CI uploads job.json only as an artifact; the log line is enough for this table). Writes:

    docs/standards/nena-coverage.md          per job and built layer: filled / partial / no_source, before -> after
    registry/remediation/nena_field_gaps.csv one row per job, layer and field that is partial or has no source,
                                             Required first: the gap review's and the agency request tracker's
                                             input (what to ask an agency to publish, or find another source for)
"""
import argparse
import csv
import json
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..")
DOC = os.path.join(ROOT, "docs", "standards", "nena-coverage.md")
GAPS = os.path.join(ROOT, "registry", "remediation", "nena_field_gaps.csv")
STATUS = {"f": "filled", "p": "partial", "n": "no_source"}
LOG_LINE = re.compile(r"\[([a-z]{2}-[a-z]{2})\] NENA coverage by field [^:]*: (\{.*\})\s*$")


def from_log(path):
    """{job: {layer: {field: {status, before?}}}} from the compact log line (no rows, sources or Required)."""
    out = {}
    with open(path, errors="replace") as f:
        for line in f:
            m = LOG_LINE.search(line)
            if m:
                out[m.group(1)] = {layer: {"built": True, "fields": {n: parse(v) for n, v in fields.items()}}
                                   for layer, fields in json.loads(m.group(2)).items()}
    return out


def parse(v):
    """'p!<n': partial, Required, no_source before."""
    f = {"status": STATUS[v[0]]}
    if "!" in v:
        f["required"] = True
    if "<" in v:
        f["before_status"] = STATUS[v[v.index("<") + 1]]
    return f


def from_job(path):
    with open(path) as f:
        j = json.load(f)
    return {j["job"]: j["nena_coverage"]}


def counts(fields, key="status"):
    return {s: sum(1 for f in fields.values() if f.get(key) == s) for s in STATUS.values()}


def before_status(f):
    if "before_status" in f:
        return f["before_status"]
    if "before" in f:
        b = f["before"]
        return "no_source" if not b else "filled" if b >= 1 else "partial"
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("inputs", nargs="+", help="job.json files or CI build logs")
    args = ap.parse_args()
    jobs = {}
    for p in args.inputs:
        jobs.update(from_job(p) if p.endswith(".json") else from_log(p))

    lines = ["# NENA field coverage by job", "",
             "Generated by `scripts/nena_coverage.py` from the builds' `nena_coverage` (src/open_ng911/coverage.py).",
             "Counts are fields of each built layer: filled (every feature), partial (some), no_source (none).",
             "`before` is the same layer built from the OpenAddresses schema alone; `after` maps each Source's own",
             "fields (the registry's `nena` tables); `(not rebuilt)` is a layer with no OpenAddresses-only build to compare",
             "(new in this pipeline, or not fed by OpenAddresses). Layers no Source feeds yet are left out; the gaps are",
             "in `registry/remediation/nena_field_gaps.csv`.", "",
             "| Job | Layer | Before (f/p/n) | After (f/p/n) |", "|---|---|---|---|"]
    gaps = []
    for job in sorted(jobs):
        for layer, s in jobs[job].items():
            if not s.get("built"):
                continue
            fields = s["fields"]
            now = counts(fields)
            for f in fields.values():
                f["_before"] = before_status(f)
            was = counts(fields, "_before") if any(f["_before"] for f in fields.values()) else None
            fmt = lambda c: f"{c['filled']}/{c['partial']}/{c['no_source']}"
            lines.append(f"| {job} | {layer} | {fmt(was) if was else '(not rebuilt)'} | {fmt(now)} |")
            for name, f in fields.items():
                if f["status"] != "filled":
                    gaps.append({"job": job, "layer": layer, "field": name, "required": f.get("required", ""),
                                 "status": f["status"], "fill": f.get("fill", ""),
                                 "source": "; ".join(f.get("source", [])), "derived": f.get("derived", "")})
    with open(DOC, "w") as f:
        f.write("\n".join(lines) + "\n")
    gaps.sort(key=lambda g: (g["job"], g["layer"], g["required"] is not True, g["field"]))
    with open(GAPS, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(gaps[0]) if gaps else ["job"])
        w.writeheader()
        w.writerows(gaps)
    print(f"{len(jobs)} jobs, {len(gaps)} field gaps -> {DOC}, {GAPS}")


if __name__ == "__main__":
    main()
